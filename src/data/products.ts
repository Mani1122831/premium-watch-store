// Helper Selectors
export const getMensWatches = (limit = 4): Product[] =>
  products.filter(p => p.gender === 'men').slice(0, limit);

export const getWomensWatches = (limit = 4): Product[] =>
  products.filter(p => p.gender === 'women').slice(0, limit);

export const getSmartWatches = (limit = 4): Product[] =>
  products.filter(p => p.category === 'Smart Watches').slice(0, limit);

export const getNewArrivals = (limit = 4): Product[] =>
  products.filter(p => p.isNew).slice(0, limit);

export const getBestSellers = (limit = 4): Product[] =>
  products.filter(p => p.isBestSeller).slice(0, limit);

export const getFeaturedProducts = (limit = 8): Product[] =>
  products.filter(p => p.isFeatured).slice(0, limit);

export const getProductById = (id: string): Product | undefined =>
  products.find(p => p.id === id);

export const getRelatedProducts = (product: Product, limit = 4): Product[] =>
  products
    .filter(p => p.id !== product.id && (p.category === product.category || p.gender === product.gender))
    .slice(0, limit);

export const searchProducts = (query: string): Product[] => {
  const q = query.toLowerCase().trim();
  if (!q) return [];
  return products.filter(p =>
    p.name.toLowerCase().includes(q) ||
    p.category.toLowerCase().includes(q) ||
    p.description.toLowerCase().includes(q) ||
    p.features.some(f => f.toLowerCase().includes(q)) ||
    (p.collection?.toLowerCase().includes(q) ?? false)
  );
};

export const getProductsByCollection = (collection: string): Product[] =>
  products.filter(p => p.collection?.toLowerCase() === collection.toLowerCase());
